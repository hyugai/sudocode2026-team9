"""Run the existing eval suite against the current M1 text and WAV datasets."""

from __future__ import annotations

import argparse
from datetime import datetime
from hashlib import sha256
import json
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory


ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "dataset/audio"
AUDIO_PLAN = ROOT / "outputs/audio-regeneration/m1-v1-kaggle/audio_plan.json"
OUTPUT = ROOT / "outputs/benchmark"

sys.path.insert(0, str(ROOT / "src"))
from eval.benchmark_support import DEFAULT_SCENARIOS, audio_path


def prepare_audio(files: list[Path], metadata: dict, bundle: Path) -> None:
    rendered = "results" in metadata
    rows = {}
    for row in metadata["results" if rendered else "tasks"]:
        key = (row["scenario_id"], row["call_id"], row["turn"])
        if key in rows:
            raise ValueError(f"Duplicate turn in audio metadata: {key}")
        rows[key] = row

    audio_root = bundle / "audio"
    scenarios = bundle / "scenarios"
    scenarios.mkdir(parents=True)
    with (bundle / "manifest.jsonl").open("w", encoding="utf-8") as manifest:
        for path in files:
            raw = path.read_bytes()
            if sha256(raw).hexdigest() != metadata["source_file_sha256"][path.name]:
                raise ValueError(f"Scenario differs from the audio source: {path.name}")
            scenario = json.loads(raw)
            sid = scenario["scenario_id"]
            for call, spec in scenario["calls"].items():
                noise_flags = set()
                for turn, source_text in enumerate(spec["customer_turns"], 1):
                    key = (path.stem, call, turn)
                    row = rows.get(key)
                    if (
                        row is None
                        or row["text_original"] != source_text
                        or row["source_scenario_id"] != sid
                    ):
                        raise ValueError(f"Audio metadata does not match the scenario turn: {key}")
                    source = audio_path(AUDIO, *key)
                    wav = source.read_bytes()
                    digest = sha256(wav).hexdigest()
                    if rendered and digest != row["sha256"]:
                        raise ValueError(f"WAV checksum differs from the render manifest: {source}")

                    target = audio_path(audio_root, sid, call, turn)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(wav)
                    noise_flags.add(bool(row["noise_code"] if rendered else row["requires_noise"]))
                    manifest.write(json.dumps({
                        "scenario_id": sid,
                        "call_id": call,
                        "turn_number": turn,
                        "text_original": source_text,
                        "output_sha256": digest,
                        "status": "generated",
                    }, ensure_ascii=False) + "\n")
                if len(noise_flags) > 1:
                    raise ValueError(f"Conflicting audio noise labels for {path.stem}/{call}")
                spec["audio_noisy"] = True in noise_flags
            (scenarios / path.name).write_text(
                json.dumps(scenario, ensure_ascii=False), encoding="utf-8"
            )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=["paired", "text", "audio", "asr"], default="paired")
    parser.add_argument("--limit", type=int, help="Use the first N eligible scenario files")
    parser.add_argument("--version", help="Output directory name (automatically generated by default)")
    parser.add_argument("--preflight-only", action="store_true")
    parser.add_argument("--llm-provider")
    parser.add_argument("--llm-model")
    parser.add_argument("--audio-manifest", type=Path, help="Final audio_manifest.json from the WAV export")
    args = parser.parse_args()

    version = args.version or f"benchmark_m1_{args.mode}_{datetime.now():%Y%m%d%H%M%S%f}"
    if Path(version).name != version or version in {".", ".."}:
        parser.error("--version must be a single directory name")
    bundle_path = OUTPUT / f"inputs_{version}"
    if not args.preflight_only and ((OUTPUT / version).exists() or bundle_path.exists()):
        parser.error("Output already exists; choose a new --version")

    files = sorted(DEFAULT_SCENARIOS.glob("SC-*.json"))
    metadata = None
    local_manifest = AUDIO.parent / "audio_manifest.json"
    if args.mode != "text":
        metadata_path = args.audio_manifest or (local_manifest if local_manifest.is_file() else AUDIO_PLAN)
        try:
            metadata = json.loads(metadata_path.read_bytes())
            source_files = metadata["source_file_sha256"]
            missing = source_files.keys() - {path.name for path in files}
            if missing:
                raise ValueError(f"Missing scenario files: {', '.join(sorted(missing))}")
            files = [path for path in files if path.name in source_files]
        except (OSError, ValueError, KeyError) as exc:
            parser.error(f"Cannot load audio metadata from {metadata_path}: {exc}")
        print(f"[M1 inputs] {metadata_path}", flush=True)
        if "results" not in metadata:
            print("[M1 inputs] Noise labels come from the generation plan. WAV checksums are calculated locally.", flush=True)

    if not files:
        parser.error(f"No matching scenario files in {DEFAULT_SCENARIOS}")
    limit = len(files) if args.limit is None else args.limit
    if not 1 <= limit <= len(files):
        parser.error(f"--limit must be between 1 and {len(files)} for mode {args.mode}")

    command = [sys.executable, "-u", "-X", "utf8", str(ROOT / "src/eval/run_suite.py"),
               "--version", version, "--limit", str(limit)]
    if args.preflight_only:
        command.append("--preflight-only")
    for flag, value in (("--llm-provider", args.llm_provider), ("--llm-model", args.llm_model)):
        if value:
            command.extend([flag, value])

    if metadata is None:
        command.extend(["--scenarios", str(DEFAULT_SCENARIOS), "--input-kinds", "text"])
        return subprocess.run(command, cwd=ROOT).returncode

    OUTPUT.mkdir(parents=True, exist_ok=True)
    try:
        with TemporaryDirectory(prefix=".m1-inputs-", dir=OUTPUT) as work:
            bundle = Path(work) / "bundle"
            prepare_audio(files[:limit], metadata, bundle)
            if not args.preflight_only:
                bundle = bundle.rename(bundle_path)
            command.extend(["--scenarios", str(bundle / "scenarios"), "--audio-root", str(bundle / "audio")])
            if args.mode == "asr":
                command.append("--asr-only")
            elif args.mode == "audio":
                command.extend(["--input-kinds", "audio"])
            return subprocess.run(command, cwd=ROOT).returncode
    except (OSError, ValueError, KeyError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    raise SystemExit(main())
